const within = (path, prefix) => path === prefix || path.startsWith(`${prefix}/`);
const emptyStats = () => ({ files: 0, nonEmpty: 0, blank: 0, lines: 0 });
function addStats(target, source) {
  for (const key of Object.keys(emptyStats())) target[key] += source[key];
}

function countLines(source) {
  if (!source) return { ...emptyStats(), files: 1 };
  const lines = source.split(/\r\n|\n|\r/);
  if (lines.at(-1) === "") lines.pop();
  const blank = lines.filter(line => line.trim() === "").length;
  return { files: 1, nonEmpty: lines.length - blank, blank, lines: lines.length };
}

function listProjects(roots) {
  return roots
    .flatMap(group =>
      readdirSync(resolve(root, group), { withFileTypes: true })
        .filter(entry => entry.isDirectory())
        .map(entry => `${group}/${entry.name}`)
        .filter(project =>
          ["package.json", "Cargo.toml"].some(file => existsSync(resolve(root, project, file)))
        )
    )
    .sort();
}

function listFiles(project) {
  return [
    ...new Set(
      execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "-z"], {
        cwd: resolve(root, project),
        encoding: "utf8",
        maxBuffer: 32 * 1024 * 1024,
      })
        .split("\0")
        .filter(Boolean)
    ),
  ].sort();
}

function excludedByPath(project, file) {
  const path = `${project}/${file}`;
  if (ownedGeneratedPaths.has(path)) return false;
  if (excludedFiles.has(path)) return true;
  const parts = file.split("/");
  const filename = parts.pop();
  return (
    parts.some(part => part.startsWith(".") || excludedDirectories.has(part.toLowerCase())) ||
    filename.startsWith(".") ||
    excludedFilename.test(filename) ||
    configFilename.test(filename)
  );
}

function collect(projects, options) {
  const total = emptyStats();
  const groups = new Map();
  const languages = new Map();
  const results = [];
  const files = [];
  for (const project of projects) {
    const stats = { project, ...emptyStats(), languages: [] };
    const projectLanguages = new Map();
    for (const file of listFiles(project)) {
      const path = `${project}/${file}`;
      const language = languageByExtension.get(extname(file).toLowerCase());
      if (!language || (options.languages.size && !options.languages.has(language))) continue;
      if (options.excludes.some(prefix => within(path, prefix)) || excludedByPath(project, file))
        continue;
      const absolute = resolve(root, path);
      let source;
      try {
        if (!lstatSync(absolute).isFile()) continue;
        source = readFileSync(absolute, "utf8");
      } catch (error) {
        if (error.code === "ENOENT") continue;
        throw error;
      }
      if (source.includes("\0") || generatedHeader.test(source.slice(0, 2048))) continue;
      const counts = countLines(source);
      addStats(stats, counts);
      if (!projectLanguages.has(language)) projectLanguages.set(language, emptyStats());
      addStats(projectLanguages.get(language), counts);
      if (options.files) files.push({ path, project, language, ...counts });
    }
    if (!stats.files) continue;
    stats.languages = sortedStats(projectLanguages, "language");
    results.push(stats);
    addStats(total, stats);
    const group = project.split("/")[0];
    if (!groups.has(group)) groups.set(group, emptyStats());
    addStats(groups.get(group), stats);
    for (const item of stats.languages) {
      if (!languages.has(item.language)) languages.set(item.language, emptyStats());
      addStats(languages.get(item.language), item);
    }
  }
  return {
    metric: "nonEmpty",
    commentsIncluded: true,
    total,
    groups: sortedStats(groups, "group"),
    languages: sortedStats(languages, "language"),
    projects: results.sort(
      (left, right) => right.nonEmpty - left.nonEmpty || left.project.localeCompare(right.project)
    ),
    ...(options.files ? { files } : {}),
  };
}

function sortedStats(map, key) {
  return [...map]
    .map(([name, stats]) => ({ [key]: name, ...stats }))
    .sort((left, right) => right.nonEmpty - left.nonEmpty || left[key].localeCompare(right[key]));
}

function printTable(title, entries, key) {
  const number = value => value.toLocaleString("en-US");
  const rows = [
    [title, "文件数", "非空行", "空行", "总行数"],
    ...entries.map(entry => [
      entry[key],
      ...[entry.files, entry.nonEmpty, entry.blank, entry.lines].map(number),
    ]),
  ];
  const width = value =>
    [...value].reduce((sum, char) => sum + (char.codePointAt(0) > 127 ? 2 : 1), 0);
  const widths = rows[0].map((_, index) => Math.max(...rows.map(row => width(row[index]))));
  for (const row of rows) {
    console.log(
      row
        .map((cell, index) => {
          const padding = " ".repeat(widths[index] - width(cell));
          return index === 0 ? cell + padding : padding + cell;
        })
        .join("  ")
    );
  }
  console.log();
}

// 报告模板是多文件，生成时内联成单文件，便于直接打开或转发
function writeHtmlReport(report, scope) {
  const templateDir = resolve(root, "scripts/code-stats-report");
  const read = file => readFileSync(resolve(templateDir, file), "utf8");
  const data = {
    generatedAt: new Date().toLocaleString("zh-CN", { hour12: false }),
    scope,
    groups: report.groups.map(group => group.group),
    files: report.files.map(file => [file.path, file.language, file.nonEmpty, file.blank]),
  };
  const html = read("index.html")
    .replace(
      '<link rel="stylesheet" href="style.css">',
      () => `<style>\n${read("style.css")}</style>`
    )
    .replace("/* 数据占位 */ null", () => JSON.stringify(data).replaceAll("<", "\\u003c"))
    .replace(
      /<script src="([\w-]+\.js)"><\/script>/g,
      (_, file) => `<script>\n${read(file)}</script>`
    );
  const output = resolve(root, "output/code-stats.html");
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, html);
  return output;
}

function openInBrowser(file) {
  const [command, args] =
    process.platform === "darwin"
      ? ["open", [file]]
      : process.platform === "win32"
        ? ["cmd", ["/c", "start", "", file]]
        : ["xdg-open", [file]];
  const child = spawn(command, args, { detached: true, stdio: "ignore" });
  child.on("error", () => console.log("无法自动打开浏览器，请手动打开上面的文件。"));
  child.unref();
}

function main() {
  const { values } = parseArgs({
    options: {
      project: { type: "string", multiple: true },
      language: { type: "string", multiple: true },
      exclude: { type: "string", multiple: true },
      "include-examples": { type: "boolean", default: false },
      details: { type: "boolean", default: false },
      files: { type: "boolean", default: false },
      json: { type: "boolean", default: false },
      html: { type: "boolean", default: false },
      help: { type: "boolean", short: "h", default: false },
    },
  });
  if (values.help) return help();
  const split = items =>
    (items ?? [])
      .flatMap(item => item.split(","))
      .map(item => item.trim())
      .filter(Boolean);
  const normalize = value => value.replaceAll("\\", "/").replace(/^\.\//, "").replace(/\/+$/, "");
  const filters = split(values.project).map(normalize);
  const languages = new Set(split(values.language).map(value => value.toLowerCase()));
  for (const language of languages) {
    if (!Object.hasOwn(languageExtensions, language))
      throw new Error(`不支持的语言：${language}，可用语言见 --help`);
  }
  const roots = [
    "apps",
    "packages",
    "plugins",
    ...(values["include-examples"] ? ["examples"] : []),
  ];
  const projects = listProjects(roots).filter(
    project => !filters.length || filters.some(prefix => within(project, prefix))
  );
  for (const filter of filters) {
    if (!projects.some(project => within(project, filter)))
      throw new Error(`未匹配到项目：${filter}`);
  }
  const report = collect(projects, {
    languages,
    excludes: (values.exclude ?? []).map(normalize),
    files: values.files || values.html,
  });
  if (values.html) {
    const scope = [
      filters.length ? filters.join(", ") : "",
      languages.size ? [...languages].join(", ") : "",
    ]
      .filter(Boolean)
      .join(" · ");
    const output = writeHtmlReport(report, scope);
    console.log(`已生成报告：${output}`);
    openInBrowser(output);
    return;
  }
  if (values.json) {
    console.log(JSON.stringify(report, null, 2));
    return;
  }
  console.log("自有源码统计（非空行包含注释，总行数 = 非空行 + 空行）\n");
  printTable("语言", report.languages, "language");
  printTable("项目", report.projects, "project");
  printTable("分组", [...report.groups, { group: "合计", ...report.total }], "group");
  if (values.details) {
    for (const project of report.projects)
      printTable(project.project, project.languages, "language");
  }
  if (values.files) {
    console.log("计入文件（语言 / 非空行 / 路径）");
    for (const file of report.files)
      console.log(`${file.language}\t${file.nonEmpty}\t${file.path}`);
  }
}

try {
  main();
} catch (error) {
  console.error(`代码统计失败：${error.message}`);
  process.exitCode = 1;
}
