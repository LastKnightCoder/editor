/**
 * 构建重点提炼的用户 Prompt
 */
export const HIGHLIGHTS_GENERATION_WITH_TOOLS_USER_PROMPT = (
  resourceNames: string[],
  userPrompt?: string,
): string => {
  const resourceList = resourceNames.map((name) => `- ${name}`).join("\n");

  let prompt = `
请为以下资源提炼学习重点：

**待处理的资源列表**：
${resourceList}

**重要提醒**：
1. **先获取资料内容**：请先使用工具获取上述资源的内容，不要直接提炼重点
2. **读取全文**：对于每个资源，请读取完整内容以确保理解全貌
3. **信息充分后再提炼**：确保获取了足够丰富的信息后，再开始提炼重点
`;

  if (userPrompt && userPrompt.trim()) {
    prompt += `
**用户的额外要求**：
${userPrompt}
`;
  }

  prompt += `
**最终输出**：
- 获取足够信息后，直接输出 Markdown 格式的重点提炼
- 聚焦于核心干货，精炼为主
- 使用结构化的格式组织知识点
- 用粗体标记关键概念
`;

  return prompt;
};

