import { defineI18n } from "@tau/i18n";
import { useI18n } from "@tau/i18n/react";
import { desktopI18n } from "@/app/i18n/runtime";
import zhCN from "./locales/zh-CN.json";
import zhTW from "./locales/zh-TW.json";
import enUS from "./locales/en-US.json";

export const searchMessages = defineI18n({
  fallbackLocale: "zh-CN",
  resources: { "zh-CN": zhCN, "zh-TW": zhTW, "en-US": enUS },
});
export type SearchMessageKey = Parameters<typeof searchMessages.ref>[0];
export const searchTranslator = desktopI18n.get(searchMessages);
export function useSearchI18n() {
  return useI18n(searchMessages, desktopI18n);
}
